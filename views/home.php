<h2>Cookies and Privacy</h2>
We will have cookies on this page. Our only intention is to provide a way for you to at least temporarily preserve anything you create here if you get disconnected or return to the site. For the immediate future we will not be storing any user information, anonymized or otherwise. In the longer run we may try to allow saving designs. In either case, we will collect no more data than absolutley necessary and will resell nothing. 
<h2>The Tools</h2>
<h3> Character Generator</h3>
<p>The first project here, a tool to interactively roll up a character using the LBB rules for character generation as presented and consolidated in the Traveller Book. At this time there are no plans to add expaned rules from Mercenary, High Guard, Scout, or Merchant Prince, and the like. </p>
<h3>Ship builder</h3>
<p>Like the character generator, this one will be a ship creation system based on the CT rules as presented in the Traveller Book. </p>

